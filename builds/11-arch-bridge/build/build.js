// Build script: base64-encodes the pencil sketch into a JS module (a
// <canvas> can't read a file:// image directly, so it has to arrive as a
// data URI baked into the script) and bundles src/main.js + its npm
// dependencies (three, cannon-es) into a single IIFE bundle.js that
// index.html loads with a plain <script src="bundle.js">. Chrome refuses
// bare-specifier <script type="module"> imports from file:// (null
// origin), so ES module imports would not survive a double-click; a
// bundled, non-module script does.
//
// Run: node build/build.js

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import esbuild from 'esbuild';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');

const sketchPath = path.join(root, 'sketch', 'arch-bridge.jpg');
const jpgBytes = readFileSync(sketchPath);
const dataUri = `data:image/jpeg;base64,${jpgBytes.toString('base64')}`;
const generatedPath = path.join(root, 'src', 'generated-sketch.js');
writeFileSync(
  generatedPath,
  `// AUTO-GENERATED by build/build.js -- do not hand-edit.\n` +
  `// Base64 data URI of sketch/arch-bridge.jpg, so it can be drawn on a\n` +
  `// <canvas> from file:// (a plain <img src="file://..."> path cannot be\n` +
  `// read back into canvas pixel data across the file:// origin boundary).\n` +
  `export const SKETCH_DATA_URI = ${JSON.stringify(dataUri)};\n`
);
console.log(`wrote ${path.relative(root, generatedPath)} (${(jpgBytes.length / 1024).toFixed(1)} KB source -> ${(dataUri.length / 1024).toFixed(1)} KB data URI)`);

await esbuild.build({
  entryPoints: [path.join(root, 'src', 'main.js')],
  bundle: true,
  format: 'iife',
  target: 'es2020',
  outfile: path.join(root, 'bundle.js'),
  logLevel: 'info',
});
